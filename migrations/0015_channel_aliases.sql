-- Channel name standardization and alias database.
-- Adds a curated alias table for channel name normalization.

-- Channel aliases for name standardization.
-- Maps variant names to canonical names for matching.
CREATE TABLE IF NOT EXISTS channel_aliases (
    id uuid PRIMARY KEY,
    canonical_name text NOT NULL,
    alias text NOT NULL UNIQUE,
    country text,
    category text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS channel_aliases_canonical_idx
    ON channel_aliases(canonical_name);
CREATE INDEX IF NOT EXISTS channel_aliases_alias_idx
    ON channel_aliases(alias);
CREATE INDEX IF NOT EXISTS channel_aliases_country_idx
    ON channel_aliases(country) WHERE country IS NOT NULL;

